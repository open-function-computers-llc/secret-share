<template>
<div v-if="!Object.entries(newSecret).length">
  <h2>Hey! What's your secret?</h2>
  <textarea v-model="secret"></textarea>

  <div :class="{ 'deactived': !secret }">
    <p>Select a team member to share this with, or just generate the link:</p>
    <ul class="flex flex-wrap justify-content-center">
      <li v-for="(r, index) in availableRecipients" :key="'recipient-' + index" :class="{ 'active': isSelected(r) }">
        <a href="#" class="button" @click.prevent="toggle(r)">{{ r === 'Nobody' ? 'Generate Link' : r }}</a>
      </li>
    </ul>

    <div class="field field--inline">
      <label for="shares">How many times do you want this secret to be viewable?</label>
      <div class="stepper">
        <button type="button" class="stepper__btn" @click="stepShares(-1)" aria-label="Decrease views">&minus;</button>
        <input id="shares" v-model="numberOfShares" type="number" min="3" max="10" />
        <button type="button" class="stepper__btn" @click="stepShares(1)" aria-label="Increase views">+</button>
      </div>
    </div>


    <label for="time">
      <p>How long should this secret be viewable?</p>
    </label>
    <select name="time" id="time" v-model="time">
      <option value="1">1 Hour</option>
      <option value="24">1 Day</option>
      <option value="168">1 Week</option>
      <option value="730">1 Month</option>
      <option value="8760">1 Year</option>
      <option value="876000">Forever</option>
    </select>

    <div class="button-wrapper">
      <button class="button" @click="store">Share</button>
    </div>
  </div>
</div>

<div v-else>
  <h2>Secret saved!</h2>
  <p>Here's the autogenerated link to view your saved secret:</p>
  <ul class="flex flex-wrap justify-content-center">
    <li><a class="button" :href="'/#/show/' + newSecret.ID" target="_blank">View</a></li>
    <li><a class="button button--copy" :class="{ copied: copied }" href="#" @click.prevent="copyLink"><span class="sizer" aria-hidden="true">Copy to clipboard</span><span class="label">{{ copied ? 'Copied!' : 'Copy to clipboard' }}</span></a></li>
  </ul>
</div>
</template>

<script>
import axios from 'axios'
export default {
  name: 'Home',
  components: {},
  data() {
    return {
      secret: "",
      numberOfShares: 5,
      time: '24',
      availableRecipients: ['Nobody'],
      selectedRecipients: ['Nobody'],
      newSecret: {}, // after the secret is saved, this will be populated with the object
      newSecretAddress: "",
      copied: false,
    }
  },
  methods: {
    toggle(r) {
      if (r === "Nobody") {
        this.selectedRecipients = ['Nobody'];
        return;
      }

      if (this.selectedRecipients.includes(r)) {
        this.selectedRecipients = this.selectedRecipients.filter((name) => name !== r);
      } else {
        this.selectedRecipients = this.selectedRecipients.filter((name) => name !== "Nobody");
        this.selectedRecipients.push(r);
      }

      if (this.selectedRecipients.length === 0) {
        this.selectedRecipients = ['Nobody'];
      }
    },
    isSelected(r) {
      return this.selectedRecipients.includes(r);
    },
    store() {
      const postData = new URLSearchParams();
      postData.append("secret", this.secret);
      postData.append("numberOfShares", this.numberOfShares);
      postData.append("shareWith", this.selectedRecipients);
      postData.append("time", this.time);

      axios.post("/api/store", postData, {
        headers: {
          'Content-Type': 'application/x-www-form-urlencoded'
        }
      }).then((r) => {
        this.newSecret = r.data.secret;
        this.newSecretAddress = r.data.url;
      }).catch(() => {
        // TODO: handle error!
      });
    },
    copyLink() {
      navigator.clipboard.writeText(this.newSecretAddress);
      this.copied = true;
      clearTimeout(this.copyTimeout);
      this.copyTimeout = setTimeout(() => {
        this.copied = false;
      }, 2000);
    },
    stepShares(delta) {
      const min = 3;
      const max = 10;
      let v = parseInt(this.numberOfShares, 10);
      if (isNaN(v)) v = min;
      this.numberOfShares = Math.min(max, Math.max(min, v + delta));
    }
  },
  mounted() {
    axios.get("/api/recipients").then((r) => {
      for (let index = 0; index < r.data.length; index++) {
        this.availableRecipients.unshift(r.data[index]);
      }
    })
  }
}
</script>

